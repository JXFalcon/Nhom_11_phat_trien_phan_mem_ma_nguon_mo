  <script>
    (function () {
      const backtop = document.getElementById('sfBacktop');
      if (backtop) {
        const sync = () => backtop.classList.toggle('is-visible', window.scrollY > 420);
        window.addEventListener('scroll', sync, { passive: true });
        sync();
        backtop.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));
      }

      const toast = document.getElementById('sfToast');
      const toastMsg = document.getElementById('sfToastMsg');
      let toastTimer = null;
      window.sfToast = function (message) {
        if (!toast || !toastMsg) return;
        toastMsg.textContent = message;
        toast.classList.add('is-show');
        clearTimeout(toastTimer);
        toastTimer = setTimeout(() => toast.classList.remove('is-show'), 2800);
      };

      const form = document.getElementById('sfNewsletter');
      if (form) {
        form.addEventListener('submit', function (e) {
          e.preventDefault();
          const input = form.querySelector('input[type="email"]');
          const value = (input && input.value || '').trim();
          if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value)) {
            window.sfToast && window.sfToast('Vui lòng nhập email hợp lệ.');
            if (input) input.focus();
            return;
          }
          window.sfToast && window.sfToast('Đã đăng ký nhận ưu đãi thành công!');
          form.reset();
        });
      }
    })();
  </script>

